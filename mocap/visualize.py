"""Headless visualisation of diffusion-decoder validation: comparison grids, probe-motion panels, videos.

Every figure is rendered off-screen (Pillow for the grids and for an orthographic projection of the
3-D probe motion, PyAV/libx264 for the videos), so no window, OpenGL context or display server is
required. matplotlib's mplot3d is deliberately not used: in this environment an older system copy
of mpl_toolkits shadows the one of the installed matplotlib.

Row layout, shared by the grids and the video frames:

    Zero motion | Context (GT) || Predicted | Target (GT) || Abs. error x3 | Probe motion (3-D)

    Labels of generated columns are red, ground-truth (GT) columns green; the double bars mark
    thick white dividers between generated and recorded images.

    Zero motion   decoder output for the context image and a zero action (ablation of motion)
    Context       real preprocessed frame I_a
    Predicted     decoder output for I_a and the measured motion a -> b
    Target        real preprocessed frame I_b
    Abs. error    3 |Predicted - Target|, clipped to [0, 1]
    Probe motion  probe trajectory between the two frames with the real probe orientations in the
                  Polaris frame: RGB axis triads (red x, green y, blue z, as in
                  Canonical_US/rgbd_bag.py) at the start, along the path and at the end, plus a
                  thin ghost of the start orientation at the end position.
"""
from pathlib import Path
import numpy as np
from PIL import Image, ImageDraw, ImageFont
from scipy.spatial.transform import Rotation

BACKGROUND, SEPARATOR, TEXT = (32, 32, 32), (150, 150, 150), (255, 255, 255)
GENERATED, GROUND_TRUTH = (255, 82, 82), (76, 217, 100)
# Column labels and colours: red = generated by the diffusion decoder, green = recorded frames.
COLUMNS = [('Zero motion', GENERATED), ('Context (GT)', GROUND_TRUTH), ('Predicted', GENERATED),
           ('Target (GT)', GROUND_TRUTH), ('Abs. error x3', TEXT), ('Probe motion', TEXT)]
BAR = 4          # thickness in pixels of the separators between rows and columns
WIDE_BAR = 16    # thicker, brighter separator between generated and ground-truth columns
WIDE_AFTER = {1, 3}   # after Context (GT) | before Predicted, and after Target (GT) | before the error


def font(size):
    # Pillow >= 10.1 ships a scalable FreeType font, so the label size does not depend on the host.
    return ImageFont.load_default(size=size)


def to_pixels(image):
    """[1, S, S] or [S, S] tensor/array in [0, 1] -> uint8 RGB [S, S, 3]."""
    array = image.squeeze().float().cpu().numpy() if hasattr(image, 'float') else np.asarray(image, dtype=np.float32).squeeze()
    gray = (array.clip(0, 1) * 255).round().astype(np.uint8)
    return np.repeat(gray[..., None], 3, axis=2)


def tracker_positions(poses):
    """Positions (mm, relative to the first pose) and absolute orientations in the tracker frame.

    Orientations are kept in the Polaris frame, which is the same for every recording, so the
    triads show the real orientation of the probe and differ between pairs. Only the origin is
    moved to the first pose, to centre the drawing.
    """
    return (poses[:, :3, 3] - poses[0, :3, 3]) * 1000, poses[:, :3, :3]


def view_basis(elevation=25., azimuth=-60.):
    """Orthographic camera: screen right and up vectors for a viewer at (elevation, azimuth) degrees."""
    el, az = np.radians(elevation), np.radians(azimuth)
    towards_viewer = np.array([np.cos(el) * np.cos(az), np.cos(el) * np.sin(az), np.sin(el)])
    right = np.cross([0., 0., 1.], towards_viewer)
    right /= np.linalg.norm(right)
    return right, np.cross(towards_viewer, right)


def blend(colour, alpha):
    return tuple(int(round(alpha * c + (1 - alpha) * b)) for c, b in zip(colour, BACKGROUND))


def motion_panel(poses, times, start, end, size, current=None, caption='', supersample=3):
    """Render the probe motion from frame `start` to frame `end` as an RGB uint8 [size, 1.5 size, 3].

    The trajectory uses every cached pose between the two frames, drawn with the real probe
    orientations in the Polaris frame (origin at the start position). Triads: start pose (faded),
    intermediate poses along the path (small, faint), current/end pose (solid), and a thin ghost of
    the start orientation at the end position, which makes the rotation between the two frames
    directly visible. A fixed orthographic view (elevation 25, azimuth -60 degrees) of a cube
    centred on the path keeps metric proportions on all axes. With `current` (videos), the path up
    to `current` is solid, the remainder dotted. The drawing is supersampled and downscaled.
    """
    width, height = int(round(1.5 * size)), size
    current = end if current is None else current
    positions, rotations = tracker_positions(poses[start:end + 1])
    k = current - start
    # Scene extent: a cube that contains the path, with a minimum side so that a nearly static
    # probe still shows legible triads; the triad length is proportional to the cube.
    centre = (positions.max(0) + positions.min(0)) / 2
    half = max(np.ptp(positions, axis=0).max() / 2, 2.) * 1.25
    length = half * .55
    right, up = view_basis()
    corners = np.array([[x, y, z] for x in (-1, 1) for y in (-1, 1) for z in (-1, 1)]) * half + centre
    s = supersample
    big = Image.new('RGB', (width * s, height * s), BACKGROUND)
    draw = ImageDraw.Draw(big)
    text_size = max(9, size // 17)
    top = 2.6 * text_size * s if caption else 1.6 * text_size * s
    # Fit the projected cube in the drawing area below the text lines.
    flat = np.stack([corners @ right, corners @ up], 1)
    lo, hi = flat.min(0), flat.max(0)
    scale = min((width * s * .94) / (hi[0] - lo[0]), (height * s - top - 4 * s) / (hi[1] - lo[1]))
    offset = np.array([width * s / 2, top + (height * s - top) / 2])
    mid = (lo + hi) / 2

    def project(points):
        points = np.atleast_2d(points)
        xy = (np.stack([points @ right, points @ up], 1) - mid) * scale
        return [(offset[0] + x, offset[1] - y) for x, y in xy]

    c = project(corners)
    for i in range(8):
        for j in range(i + 1, 8):
            if bin(i ^ j).count('1') == 1:   # cube edges join corners that differ in one coordinate
                draw.line([c[i], c[j]], fill=(78, 78, 78), width=s)
    path = project(positions)
    if k > 0:
        draw.line(path[:k + 1], fill=(79, 195, 247), width=2 * s, joint='curve')
    for i in range(k, len(path) - 1, 2):     # remaining path, dotted
        draw.line(path[i:i + 2], fill=(150, 150, 150), width=s)
    stride = max(1, len(positions) // 6)
    triads = [(positions[i], rotations[i], .3, .6, 1.5) for i in range(stride, k, stride)]   # intermediate
    triads += [(positions[0], rotations[0], .5, 1., 3),            # start orientation
               (positions[k], rotations[0], .55, 1., 1),           # ghost: start orientation at the end position
               (positions[k], rotations[k], 1., 1., 3)]            # current / end orientation
    for origin, rotation, alpha, scale_length, line in triads:
        for axis, colour in enumerate([(255, 59, 48), (52, 199, 89), (10, 132, 255)]):
            a, b = project(np.stack([origin, origin + rotation[:, axis] * length * scale_length]))
            draw.line([a, b], fill=blend(colour, alpha), width=max(1, int(line * s)))
    for point, colour, r in [(path[0], (255, 255, 255), 3), (path[k], (255, 214, 10), 4)]:
        draw.ellipse([point[0] - r * s, point[1] - r * s, point[0] + r * s, point[1] + r * s], fill=colour)
    translation = np.linalg.norm(positions[k])
    angle = np.degrees(np.linalg.norm(Rotation.from_matrix(rotations[0].T @ rotations[k]).as_rotvec()))
    dt = (times[current] - times[start]) / 1e9
    label = font(text_size * s)
    draw.text((4 * s, 3 * s), f'dt {dt:.2f} s  |t| {translation:.1f} mm  rot {angle:.1f} deg', fill=TEXT, font=label)
    small = font(max(8, int(text_size * .8)) * s)
    if caption:
        draw.text((4 * s, 3 * s + 1.3 * text_size * s), caption, fill=(189, 189, 189), font=small)
    draw.text((4 * s, height * s - 3 * s), f'cube {2 * half:.0f} mm', fill=(189, 189, 189), font=small, anchor='ld')
    # Gizmo of the Polaris (world) axes, in grey to distinguish it from the RGB probe triads.
    reach = max(10, size // 9) * s
    g = np.array([width * s - 1.6 * reach, height * s - 1.5 * reach])
    for axis, name in enumerate('XYZ'):
        d = np.array([right[axis], -up[axis]]) * reach
        draw.line([tuple(g), tuple(g + d)], fill=(170, 170, 170), width=2 * s)
        draw.text(tuple(g + d * 1.35), name, fill=(200, 200, 200), font=small, anchor='mm')
    draw.text((width * s - 3 * s, height * s - 2 * s), 'Polaris', fill=(150, 150, 150), font=small, anchor='rd')
    return np.asarray(big.resize((width, height), Image.Resampling.LANCZOS))


def compose(rows, header=None):
    """Stack rows of equally tall RGB panels with labelled columns and separator bars."""
    size = rows[0][0].shape[0]
    widths = [panel.shape[1] for panel in rows[0]]
    label_font = font(max(14, size // 9))
    head = int(label_font.size * 1.8)
    extra = int(label_font.size * 1.6) if header else 0
    gaps = [WIDE_BAR if j in WIDE_AFTER else BAR for j in range(len(widths) - 1)]
    width = sum(widths) + sum(gaps)
    height = extra + head + len(rows) * size + BAR * len(rows)
    canvas = Image.new('RGB', (width, height), BACKGROUND)
    draw = ImageDraw.Draw(canvas)
    if header:
        draw.text((8, extra // 2), header, fill=TEXT, font=label_font, anchor='lm')
    x = 0
    for j, ((label, colour), w) in enumerate(zip(COLUMNS, widths)):
        draw.text((x + w // 2, extra + head // 2), label, fill=colour, font=label_font, anchor='mm')
        x += w
        if j < len(gaps):
            if gaps[j] == WIDE_BAR:   # full-height divider, labels included
                draw.rectangle([x + 3, extra, x + gaps[j] - 4, height - 1], fill=TEXT)
            x += gaps[j]
    y = extra + head
    for row in rows:
        draw.rectangle([0, y, width, y + BAR - 1], fill=SEPARATOR)   # horizontal bar above each row
        y += BAR
        x = 0
        for j, panel in enumerate(row):
            canvas.paste(Image.fromarray(panel), (x, y))
            x += panel.shape[1]
            if j < len(gaps):
                if gaps[j] == BAR:
                    draw.rectangle([x, y, x + BAR - 1, y + size - 1], fill=SEPARATOR)
                x += gaps[j]
        y += size
    return canvas


def save_grids(rows, output, per_file=12):
    """Write comparison1.png, comparison2.png, ... with `per_file` rows each."""
    paths = []
    for start in range(0, len(rows), per_file):
        path = Path(output) / f'comparison{start // per_file + 1}.png'
        compose(rows[start:start + per_file]).save(path)
        paths.append(path)
    return paths


def save_video(frames, path, fps):
    """Encode RGB uint8 frames with libx264 (yuv420p requires even dimensions)."""
    import av
    h, w = frames[0].shape[:2]
    h, w = h - h % 2, w - w % 2
    with av.open(str(path), mode='w') as container:
        stream = container.add_stream('libx264', rate=fps)
        stream.width, stream.height, stream.pix_fmt = w, h, 'yuv420p'
        stream.options = {'crf': '18'}
        for frame in frames:
            for packet in stream.encode(av.VideoFrame.from_ndarray(np.ascontiguousarray(frame[:h, :w]), format='rgb24')):
                container.mux(packet)
        for packet in stream.encode():
            container.mux(packet)
